RESALABLE_REASONS = {"Customer Preference", "Wrong Item"}

def load_real_data(
    data_dir: str = "/mnt/user-data/uploads/",
    level: str    = "category",        # "category" (recommended) or "product"
) -> dict:
    if level not in ("category", "product"):
        raise ValueError("level must be 'category' or 'product'")

    # ── Load CSVs ─────────────────────────────────────────────────────────
    orders      = pd.read_csv(data_dir + "orders.csv",      parse_dates=["order_date"])
    order_items = pd.read_csv(data_dir + "order_items.csv")
    products    = pd.read_csv(data_dir + "products.csv")
    categories  = pd.read_csv(data_dir + "categories.csv")
    returns     = pd.read_csv(data_dir + "returns.csv",     parse_dates=["return_date"])

    # ── Completed orders only ─────────────────────────────────────────────
    completed        = orders[orders["order_status"] == "Completed"].copy()
    completed["week_period"] = completed["order_date"].dt.to_period("W")

    # ── Master items table ────────────────────────────────────────────────
    items = (
        order_items
        .merge(completed[["order_id", "order_date", "week_period"]], on="order_id", how="inner")
        .merge(products[["product_id", "product_name", "category_id"]],               on="product_id")
        .merge(categories,                                                             on="category_id")
    )
    # Intraperiod fraction: which day of the week did the order arrive?
    items["arrival_frac"] = items["order_date"].dt.dayofweek / 7.0

        # Prefer an explicit quantity column in returns.csv if it exists.
    # Otherwise fall back to the order_items.quantity for that order_item_id.
    if "quantity" in returns.columns:
        returns = returns.rename(columns={"quantity": "return_qty"})
    else:
        returns["return_qty"] = np.nan

    returns = returns.merge(
        order_items[["order_item_id", "quantity"]].rename(columns={"quantity": "order_item_qty"}),
        on="order_item_id",
        how="left",
    )

    # Final fallback: if both are missing, treat one return record as 1 unit.
    returns["return_qty"] = (
        returns["return_qty"]
        .fillna(returns["order_item_qty"])
        .fillna(1)
        .clip(lower=0)
        .astype(int)
    )
    returns.drop(columns=["order_item_qty"], inplace=True)


    # ── Returns with resalability flag ────────────────────────────────────
    returns["is_resalable"]  = returns["return_reason"].isin(RESALABLE_REASONS)
    returns["week_period"]   = returns["return_date"].dt.to_period("W")
    returns["return_frac"]   = returns["return_date"].dt.dayofweek / 7.0

    # Link returns → product / category
    ret_linked = (
    returns
    .merge(order_items[["order_item_id", "order_id", "product_id"]], on="order_item_id", how="left")
    .merge(products[["product_id", "product_name", "category_id"]],  on="product_id",   how="left")
    .merge(categories,                                                on="category_id",  how="left")
    # ── COHORT FIX: attach the sale week via the originating order ────────
    .merge(completed[["order_id", "week_period"]].rename(
               columns={"week_period": "sale_week_period"}),
           on="order_id", how="left")
)

    ret_linked["days_to_return"] = (
            ret_linked["return_date"] -
            ret_linked.merge(
                orders[["order_id", "order_date"]],
                on="order_id", how="left"
            )["order_date"]
        ).dt.days

    print(ret_linked["days_to_return"].describe())
    print("\nReturn timing distribution:")
    print(pd.cut(ret_linked["days_to_return"],
                    bins=[0, 7, 14, 30, 60, 999],
                    labels=["0-7 days", "8-14 days", "15-30 days",
                            "31-60 days", "60+ days"]).value_counts())


    # ── Shared week calendar (all periods that exist in the data) ─────────
    all_periods = sorted(items["week_period"].unique())

    # ── Grouping key ──────────────────────────────────────────────────────
    if level == "category":
        group_key   = "category_name"
        group_names = categories["category_name"].tolist()
    else:
        group_key   = "product_name"
        group_names = products["product_name"].tolist()

    datasets = {}

    for name in group_names:
        items_g   = items[items[group_key] == name]
        returns_g = ret_linked[ret_linked[group_key] == name]

        if items_g.empty:
            continue

        # ── Gt, ut, k_obs_t per week ──────────────────────────────────────
        Gt = (items_g.groupby("week_period")["quantity"]
                     .sum()
                     .reindex(all_periods, fill_value=0)
                     .rename("Gt")
                     .astype(int))

        # ── COHORT FIX: cohort returns to their sale week, not return week ─────
        # This ensures ut <= Gt by construction and makes the binomial
        # model U_t | G_t ~ Binomial(G_t, r_hat) coherent.
        ut = (returns_g.groupby("sale_week_period")["return_qty"]
              .sum()
              .reindex(all_periods, fill_value=0)
              .rename("ut")
              .astype(int))

        kt = (returns_g[returns_g["is_resalable"]]
              .groupby("sale_week_period")["return_qty"]
              .sum()
              .reindex(all_periods, fill_value=0)
              .rename("k_obs_t")
              .astype(int))

        # ── Build df ──────────────────────────────────────────────────────
        # week_num is a plain integer index (0, 1, 2, …) used by
        # build_net_demand_matrix which accesses lists via df.iterrows() index.
        # week is a readable label kept for reporting / plots.
        df = pd.DataFrame({
            "week_num" : range(len(all_periods)),          # 0-based int index
            "week"     : [str(p) for p in all_periods],   # human-readable label
            "Gt"       : Gt.values,
            "ut"       : ut.values,
            "k_obs_t"  : kt.values,
        })

        # ── Intraperiod arrival fractions ─────────────────────────────────
        arrival_times        = []
        return_arrival_times = []

        for period in all_periods:
              # Demand arrivals (expand to one timestamp per UNIT)
              mask_d = items_g["week_period"] == period
              d_fracs = items_g.loc[mask_d, "arrival_frac"].to_numpy()
              d_qty   = items_g.loc[mask_d, "quantity"].to_numpy(dtype=int)
              d_expanded = np.repeat(d_fracs, d_qty)
              arrival_times.append(np.sort(d_expanded))

              # Return arrivals (expand to one timestamp per returned UNIT)
              mask_r = returns_g["week_period"] == period
              r_fracs = returns_g.loc[mask_r, "return_frac"].to_numpy()
              r_qty   = returns_g.loc[mask_r, "return_qty"].to_numpy(dtype=int)
              r_expanded = np.repeat(r_fracs, r_qty)
              return_arrival_times.append(np.sort(r_expanded))
        datasets[name] = (df, arrival_times, return_arrival_times)

    # ── Summary print ─────────────────────────────────────────────────────
    print("=" * 66)
    print(f"REAL DATA LOADED  —  level='{level}'")
    print("=" * 66)
    print(f"  {'Name':<28} {'Weeks':>6}  {'Gt':>7}  {'ut':>5}  {'k_obs':>6}  {'r_hat':>7}  {'k_hat':>7}")
    print("  " + "-" * 63)
    for n, (d, _, _) in datasets.items():
        G = d["Gt"].sum(); u = d["ut"].sum(); k = d["k_obs_t"].sum()
        r = u / G if G > 0 else 0
        kh = k / u if u > 0 else 0
        print(f"  {n:<28} {len(d):>6}  {G:>7,}  {u:>5}  {k:>6}  {r:>7.4f}  {kh:>7.4f}")
    print()

    return datasets

"""Parameter vs."""

def estimate_parameters(df: pd.DataFrame) -> dict:
    """
    Pooled MLE of r_hat (Eq. 2) and k_hat (Eq. 4).
    Skips weeks where Gt=0 to avoid division issues.
    """
    total_G = df["Gt"].sum()
    total_u = df["ut"].sum()
    total_k = df["k_obs_t"].sum()

    r_hat = total_u / total_G if total_G > 0 else 0.0
    k_hat = total_k / total_u if total_u > 0 else 0.0

    print(f"  r_hat (return rate)      = {r_hat:.4f}")
    print(f"  k_hat (resalability)     = {k_hat:.4f}")
    print(f"  r_hat * k_hat            = {r_hat * k_hat:.4f}")
    print()
    return {"r_hat": r_hat, "k_hat": k_hat}

"""Cost Parameter"""

def compute_cost_params(p, c, s, g, d, r_hat, k_hat) -> dict:
    """
    pG = (1-r)*p + r*k*(p-d) + r*(1-k)*(s-d)   (Eq. 6)
    pN = pG / (1 - r*k)                          (Eq. 7)
    gN = g  / (1 - r*k)                          (Eq. 7)
    """
    pG    = ((1 - r_hat) * p
             + r_hat * k_hat       * (p - d)
             + r_hat * (1 - k_hat) * (s - d))
    scale = 1.0 / (1.0 - r_hat * k_hat)
    pN    = pG * scale
    gN    = g  * scale

    ok = (pN + gN > c > s >= 0)
    print(f"  pG={pG:.4f}  pN={pN:.4f}  gN={gN:.4f}  "
          f"well-posed={'OK' if ok else 'VIOLATED'}")
    print()
    return {"pG": pG, "pN": pN, "gN": gN}

"""MONTE CARLO SIMULATION — intraperiod order-of-arrival netting TRUE VECTORISATION: zero Python loops, runs 101 weeks x J=500 in < 1s"""

def simulate_net_demand(
    Gt: int,
    arrival_times_t: np.ndarray,
    return_arrival_times_t: np.ndarray,
    r_hat: float,
    k_hat: float,
    J: int,
    rng: np.random.Generator,
) -> np.ndarray:
    """
    J Monte Carlo replications for one historical period t — fully vectorised.

    Algorithm
    ---------
    1.  Draw U^(j) ~ Binomial(Gt, r_hat) for all j at once          (Eq. 1)
    2.  Draw K^(j) ~ Binomial(U^(j), k_hat) for all j at once       (Eq. 3)
    3.  Group replications by K to batch-process identical K values.
    4.  For each unique K:
          a. Draw (n_reps x K) return arrival fracs by resampling from
             the empirical return-timing distribution.
          b. Encode timeline:
               returns → fracs in [0, 1)    (arrive first on ties)
               demands → fracs in [1, 2)    (arrive after returns on ties)
          c. Concatenate and argsort to get chronological order.
          d. Compute cumsum of (+1 for return, -1 for demand).
             Each position where cumsum < 0 is a demand that hit an
             empty buffer → must be served from ordered stock Q.
          e. net_demand = count(cumsum < 0)

    Returns np.ndarray of shape (J,).
    """
    if Gt == 0:
        return np.zeros(J)

    # Steps 1 & 2 — draw all U and K at once
    U_all = rng.binomial(Gt,    r_hat, size=J)   # (J,)
    K_all = rng.binomial(U_all, k_hat)            # (J,)

    # Initialize net_demands here, outside the conditional block.
    net_demands = np.empty(J)

    # Demand arrival fracs — fixed for this week, same for all replications
    if len(arrival_times_t) == Gt:
        d_fracs = arrival_times_t
    elif len(arrival_times_t) > 0:
        d_fracs = np.sort(rng.choice(arrival_times_t, size=Gt, replace=True))
    else:
        d_fracs = np.sort(rng.uniform(0, 1, Gt))

    # Step 3 — group by K to avoid redundant allocations
    for K in np.unique(K_all):
        mask   = (K_all == K)
        n_reps = int(mask.sum())

        if K == 0:
            net_demands[mask] = Gt     # no returns → all demand hits stock
            continue

        # Step 4a — return arrival fracs: shape (n_reps, K)
        if len(return_arrival_times_t) > 0:
            r_fracs = rng.choice(return_arrival_times_t,
                                 size=(n_reps, K), replace=True)
        else:
            r_fracs = rng.uniform(0, 1, size=(n_reps, K))

        # Step 4b — encode: returns in [0,1), demands in [1,2)
        eps = 1e-9
        r_enc = r_fracs                                             # (n_reps, K)
        d_enc = np.broadcast_to(d_fracs, (n_reps, Gt)) + eps # (n_reps, Gt)

        # Step 4c — sort merged timeline
        times    = np.concatenate([r_enc, d_enc], axis=1)          # (n_reps, K+Gt)
        values   = np.concatenate([ np.ones((n_reps, K)),
                                   -np.ones((n_reps, Gt))], axis=1)
        order    = np.argsort(times, axis=1)
        sorted_v = np.take_along_axis(values, order, axis=1)       # (n_reps, K+Gt)

        # Step 4d-e — cumsum < 0 counts unmet demand units
        cs = np.cumsum(sorted_v, axis=1)                           # (n_reps, K+Gt)
        net_demands[mask] = np.maximum(0, -cs.min(axis=1))

    return net_demands


def build_net_demand_matrix(
    df: pd.DataFrame,
    arrival_times: list,
    return_arrival_times: list,
    r_hat: float,
    k_hat: float,
    J: int   = 500,
    seed: int = 0,
) -> np.ndarray:
    """
    Build the (m x J) matrix N[t, j] = N_t^(j).

    Loops over m weeks (outer loop, cheap) and calls the vectorised
    simulate_net_demand for each week (inner work, all NumPy).
    Typical runtime: <5s for m=101, J=500 on Colab CPU.
    """
    rng      = np.random.default_rng(seed)
    m        = len(df)
    N_matrix = np.empty((m, J))

    df_reset = df.reset_index(drop=True)
    for idx, row in df_reset.iterrows():
        N_matrix[idx] = simulate_net_demand(
            Gt                     = int(row["Gt"]),
            arrival_times_t        = arrival_times[idx],
            return_arrival_times_t = return_arrival_times[idx],
            r_hat=r_hat, k_hat=k_hat, J=J, rng=rng,
        )

    print(f"  Net demand matrix: shape={N_matrix.shape}  "
          f"mean={N_matrix.mean():.2f}  std={N_matrix.std():.2f}")
    print()
    return N_matrix

"""SAA Optimization"""

def _solve_with_gurobi(N_flat, c, s, pN, gN, Q_max, env) -> dict:
    mJ = len(N_flat)
    cu = pN - c + gN
    co = c - s

    model = gp.Model("newsvendor_saa", env=env)
    model.setParam("OutputFlag", 0)

    Q = model.addVar(lb=0.0, ub=Q_max, name="Q")
    z = model.addVars(mJ, lb=0.0, name="z")
    v = model.addVars(mJ, lb=0.0, name="v")

    for i in range(mJ):
        model.addConstr(z[i] >= N_flat[i] - Q)
        model.addConstr(v[i] >= Q - N_flat[i])

    model.setObjective(
        (cu / mJ) * gp.quicksum(z[i] for i in range(mJ))
      + (co / mJ) * gp.quicksum(v[i] for i in range(mJ)),
        GRB.MINIMIZE,
    )
    model.optimize()

    Q_opt   = float(Q.X)
    obj_opt = float(model.ObjVal)
    ESN     = float(np.mean(np.maximum(N_flat - Q_opt, 0)))
    model.dispose()
    return {"Q_opt": Q_opt, "obj_opt": obj_opt, "ESN": ESN,
            "solver": "Gurobi WLS academic"}




def _solve_with_quantile(N_flat, c, s, pN, gN) -> dict:
    """
    Exact SAA solution via the newsvendor critical-ratio formula.

    For cost  EP(Q) = cu*E[(N-Q)^+] + co*E[(Q-N)^+]  the LP optimum
    is the alpha-quantile of the empirical net-demand sample, where:

        alpha = cu / (cu + co) = (pN - c + gN) / (pN - s + gN)

    Mathematically identical to the full LP (Zipkin 2000, Prop. 2.1).
    Runs in O(mJ log mJ) time, O(mJ) memory — no solver, no RAM crash.
    """
    cu    = pN - c + gN
    co    = c  - s
    alpha = cu / (cu + co)                               # critical ratio

    Q_opt   = float(np.quantile(N_flat, alpha))
    ESN     = float(np.mean(np.maximum(N_flat - Q_opt, 0)))
    obj_opt = float(cu * ESN + co * np.mean(np.maximum(Q_opt - N_flat, 0)))

    return {"Q_opt": Q_opt, "obj_opt": obj_opt, "ESN": ESN,
            "alpha": alpha,
            "solver": f"Quantile (alpha={alpha:.4f})"}


def solve_saa(N_matrix, c, s, pN, gN, gurobi_env=None, Q_max=None) -> dict:
    m, J   = N_matrix.shape
    N_flat = N_matrix.flatten()
    if Q_max is None:
        Q_max = float(N_flat.max()) * 2.0

    if gurobi_env is not None:
        try:
            result = _solve_with_gurobi(N_flat, c, s, pN, gN, Q_max, gurobi_env)
        except Exception as e:
            warnings.warn(f"Gurobi failed ({e}) -> quantile fallback.")
            result = _solve_with_quantile(N_flat, c, s, pN, gN)
    else:
        # Default fast path: exact quantile formula (no LP, no memory issues)
        result = _solve_with_quantile(N_flat, c, s, pN, gN)

    print(f"  Solver : {result['solver']}   m={m} J={J} mJ={m*J}")
    print(f"  Q*     = {result['Q_opt']:.4f}")
    print(f"  Cost   = {result['obj_opt']:.4f}")
    print(f"  ESN    = {result['ESN']:.4f}")
    print()
    return result

"""Bencmark"""

def netting_benchmark(df, r_hat, k_hat, c, s, pN, gN, gurobi_env=None) -> dict:
    """Deterministic netting: net_demand_t = Gt * (1 - r_hat*k_hat)."""
    N_det  = (df["Gt"].values * (1.0 - r_hat * k_hat)).reshape(-1, 1)
    result = solve_saa(N_det, c, s, pN, gN, gurobi_env=gurobi_env)
    print(f"  [Benchmark] Q* = {result['Q_opt']:.4f}\n")
    return result

"""Sensitivity Analysis"""

def sensitivity_analysis(df, arrival_times, return_arrival_times,
                          base_params, r_hat, k_hat,
                          gurobi_env=None, J=200) -> pd.DataFrame:
    p, c, s, d = base_params["p"], base_params["c"], base_params["s"], base_params["d"]
    k_grid = np.linspace(0.20, 0.95, 8)
    g_grid = np.linspace(1.0,  20.0, 6)
    records = []

    for g_val in g_grid:
        for k_val in k_grid:
            cp = compute_cost_params(p, c, s, g_val, d, r_hat, k_val)
            pN_v, gN_v = cp["pN"], cp["gN"]
            if pN_v + gN_v <= c:
                continue
            N_k = build_net_demand_matrix(df, arrival_times, return_arrival_times,
                                          r_hat=r_hat, k_hat=k_val, J=J, seed=1)
            res = solve_saa(N_k, c, s, pN_v, gN_v, gurobi_env=gurobi_env)
            records.append({"g": g_val, "k_hat": k_val, "Q_opt": res["Q_opt"]})
            print(f"  g={g_val:5.1f}  k_hat={k_val:.2f}  ->  Q*={res['Q_opt']:.4f}")

    print()
    return pd.DataFrame(records)
def sensitivity_return_rate(df, arrival_times, return_arrival_times,
                             base_params, k_hat,
                             gurobi_env=None, J=100) -> pd.DataFrame:
    """
    One-dimensional sensitivity of Q* and EP(Q*) on the return rate r_hat.
    Varies r_hat over a grid [0.04, 0.16] while holding k_hat fixed at its
    category estimate and all cost parameters at their baseline values.

    Returns a DataFrame with columns: r_hat, Q_opt, cost, ESN
    """
    p, c, s, g, d = (base_params["p"], base_params["c"], base_params["s"],
                     base_params["g"], base_params["d"])

    r_grid  = np.linspace(0.04, 0.16, 13)   # 13 points, step ~0.01
    records = []

    for r_val in r_grid:
        cp = compute_cost_params(p, c, s, g, d, r_val, k_hat)
        pN_v, gN_v = cp["pN"], cp["gN"]
        if pN_v + gN_v <= c:
            print(f"  r_hat={r_val:.3f}  ->  skipped (not well-posed)")
            continue

        N_r = build_net_demand_matrix(
            df, arrival_times, return_arrival_times,
            r_hat=r_val, k_hat=k_hat, J=J, seed=2,
        )
        res = solve_saa(N_r, c, s, pN_v, gN_v, gurobi_env=gurobi_env)
        records.append({
            "r_hat": r_val,
            "Q_opt": res["Q_opt"],
            "cost":  res["obj_opt"],
            "ESN":   res["ESN"],
        })
        print(f"  r_hat={r_val:.3f}  ->  Q*={res['Q_opt']:.1f}  "
              f"Cost={res['obj_opt']:.4f}  ESN={res['ESN']:.4f}")

    print()
    return pd.DataFrame(records)

