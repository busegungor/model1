def build_corner_sensitivity_table(all_sens: dict) -> pd.DataFrame:
    """
    Compact cross-category comparison table.
    Shows Q* only at the four corners of the sensitivity grid:
        g ∈ {1.0, 20.0}  x  k̂ ∈ {0.20, 0.95}
    Returns a wide-format DataFrame suitable for printing or LaTeX export.
    """
    corners = [(1.0, 0.20), (1.0, 0.95), (20.0, 0.20), (20.0, 0.95)]
    col_labels = ["g=1.0, k̂=0.20", "g=1.0, k̂=0.95",
                  "g=20.0, k̂=0.20", "g=20.0, k̂=0.95"]

    rows = []
    for cat_name, sens_df in all_sens.items():
        row = {"Category": cat_name}
        for (g_val, k_val), col in zip(corners, col_labels):
            # Find the closest grid point (handles floating point rounding)
            match = sens_df[
                (np.isclose(sens_df["g"],     g_val, atol=0.05)) &
                (np.isclose(sens_df["k_hat"], k_val, atol=0.05))
            ]
            row[col] = int(round(match["Q_opt"].values[0])) if len(match) > 0 else np.nan
        rows.append(row)

    return pd.DataFrame(rows)




