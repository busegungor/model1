def plot_all_cost_curves(all_cost_data: dict,
                          save_path="cost_curves_all_categories.png"):
    """
    Multi-panel EP(Q) cost curves for all five categories.

    all_cost_data: dict { cat_name -> {
        "N_flat"  : np.ndarray (flattened net demand),
        "c"       : float,
        "s"       : float,
        "pN"      : float,
        "gN"      : float,
        "Q_stoch" : float,
        "Q_bench" : float,
    }}
    """
    categories = list(all_cost_data.keys())
    n     = len(categories)
    ncols = 3
    nrows = (n + ncols - 1) // ncols   # 2 rows for 5 categories

    fig, axes = plt.subplots(nrows, ncols, figsize=(15, 9))
    axes_flat = axes.flatten()

    for ax_idx, cat in enumerate(categories):
        ax   = axes_flat[ax_idx]
        d    = all_cost_data[cat]
        N_flat  = d["N_flat"]
        cu   = d["pN"] - d["c"] + d["gN"]
        co   = d["c"]  - d["s"]

        # EP(Q) curve
        Q_grid = np.linspace(N_flat.min() * 0.3, N_flat.max() * 1.5, 400)
        EP = np.array([
            cu * np.mean(np.maximum(N_flat - q, 0))
          + co * np.mean(np.maximum(q - N_flat, 0))
            for q in Q_grid
        ])

        # EP values at the two optima
        EP_stoch = float(cu * np.mean(np.maximum(N_flat - d["Q_stoch"], 0))
                       + co * np.mean(np.maximum(d["Q_stoch"] - N_flat, 0)))
        EP_bench = float(cu * np.mean(np.maximum(N_flat - d["Q_bench"], 0))
                       + co * np.mean(np.maximum(d["Q_bench"] - N_flat, 0)))

        ax.plot(Q_grid, EP, color="#2166ac", lw=2, label="EP(Q)")

        # Stochastic optimum
        ax.axvline(d["Q_stoch"], color="#2166ac", ls="--", lw=1.8,
                   label=f"$Q^*_{{\\rm stoch}}={d['Q_stoch']:.0f}$")
        ax.scatter(d["Q_stoch"], EP_stoch,
                   color="#2166ac", s=70, zorder=5)

        # Benchmark optimum
        ax.axvline(d["Q_bench"], color="#d6604d", ls="--", lw=1.8,
                   label=f"$Q^*_{{\\rm bench}}={d['Q_bench']:.1f}$")
        ax.scatter(d["Q_bench"], EP_bench,
                   color="#d6604d", s=70, zorder=5)

        # Shaded cost gap between the two optima
        ax.fill_between(
            [min(d["Q_stoch"], d["Q_bench"]),
             max(d["Q_stoch"], d["Q_bench"])],
            0, max(EP_stoch, EP_bench),
            alpha=0.12, color="#fdae61",
        )

        # Horizontal dotted lines at each minimum cost level
        ax.axhline(EP_stoch, color="#2166ac", ls=":", lw=1.2, alpha=0.7)
        ax.axhline(EP_bench, color="#d6604d", ls=":", lw=1.2, alpha=0.7)

        ax.set_title(cat, fontsize=11, fontweight="bold", pad=5)
        ax.set_xlabel("Order Quantity $Q$", fontsize=9)
        ax.set_ylabel("Expected Total Cost $EP(Q)$", fontsize=9)
        ax.legend(fontsize=7.5, loc="upper right")
        ax.grid(True, alpha=0.3, linestyle="--")
        ax.tick_params(labelsize=8)

    # Hide unused 6th panel
    for ax in axes_flat[n:]:
        ax.set_visible(False)

    fig.suptitle(
        "SAA Expected Cost Curve $EP(Q)$ — All Categories\n"
        "Dashed lines: stochastic optimum (blue) and deterministic "
        "netting benchmark (red). Dotted lines: corresponding minimum costs.",
        fontsize=12, fontweight="bold", y=1.01,
    )
    plt.tight_layout()
    plt.savefig(save_path, dpi=180, bbox_inches="tight")
    plt.close()
    print(f"  Saved: {save_path}")


